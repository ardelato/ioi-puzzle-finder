function FilterWidgetTemporary(string $target): string
{
    $temporary = @tempnam(dirname($target), '.filters-');
    if ($temporary === false || realpath(dirname($temporary)) !== realpath(dirname($target))) {
        if (is_string($temporary) && is_file($temporary)) { unlink($temporary); }
        throw new RuntimeException('Cannot create temporary output beside ' . $target);
    }
    return $temporary;
}

/** Stage every file first, then roll back earlier replacements if a later one fails. */
function FilterWidgetCommitOutputs(array $staged): void
{
    $backups = [];
    $committed = [];
    $retainedBackups = [];
    try {
        foreach ($staged as $target => $temporary) {
            if (file_exists($target) && !is_file($target)) { throw new RuntimeException('Output is not a file: ' . $target); }
            if (is_file($target)) {
                $backups[$target] = FilterWidgetTemporary($target);
                if (!@copy($target, $backups[$target])) { throw new RuntimeException('Cannot preserve existing output: ' . $target); }
            }
        }
        foreach ($staged as $target => $temporary) {
            if (!@rename($temporary, $target)) { throw new RuntimeException('Cannot replace output: ' . $target); }
            $committed[] = $target;
        }
    } catch (Throwable $error) {
        $restoreErrors = [];
        foreach (array_reverse($committed) as $target) {
            if (isset($backups[$target])) {
                if (!@rename($backups[$target], $target)) {
                    $retainedBackups[$backups[$target]] = true;
                    $restoreErrors[] = 'Restore ' . $target . ' from ' . $backups[$target];
                }
            } elseif (is_file($target) && !@unlink($target)) {
                $restoreErrors[] = 'Cannot remove incomplete new output: ' . $target;
            }
        }
        throw new RuntimeException($error->getMessage() . ($restoreErrors === [] ? '' : '; ' . implode('; ', $restoreErrors)), 0, $error);
    } finally {
        foreach (array_merge(array_values($staged), array_values($backups)) as $path) {
            if (!isset($retainedBackups[$path]) && is_file($path)) { unlink($path); }
        }
    }
}

function FilterWidgetMain(array $argv): int
{
    $options = getopt('', ['base-widget:', 'markers:', 'output:', 'manifest:', 'help'], $next);
    foreach ($options as $key => $value) {
        if ($key === 'help' && $value === false) { continue; }
        if (!is_string($value) || $value === '') { throw new RuntimeException('Options must have one nonempty value; repeated options are invalid.'); }
    }
    if (isset($options['help'])) { echo "Usage: php filter_widget.php --base-widget FILE --markers FILE --output FILE [--manifest FILE]\n"; return 0; }
    if ($next !== count($argv) || !isset($options['base-widget'], $options['markers'], $options['output'])) { throw new RuntimeException('Provide --base-widget, --markers and --output.'); }
    $cwd = getcwd();
    $absolute = static fn(string $path): string => preg_match('~^(?:[A-Za-z]:[\\\\/]|[\\\\/])~', $path) ? $path : $cwd . DIRECTORY_SEPARATOR . $path;
    $input = realpath($absolute($options['base-widget']));
    $snapshot = realpath($absolute($options['markers']));
    if ($input === false || $snapshot === false || !is_file($input) || !is_file($snapshot)) { throw new RuntimeException('Both input files must exist.'); }
    $resolveOutput = static function (string $path) use ($absolute): string {
        $path = $absolute($path);
        $existing = realpath($path);
        if ($existing !== false) {
            if (!is_file($existing)) { throw new RuntimeException('Output is not a file: ' . $path); }
            return $existing;
        }
        $parent = realpath(dirname($path));
        if ($parent === false || !is_dir($parent) || is_link($path)) { throw new RuntimeException('Output parent directory must exist and dangling symlinks are not supported.'); }
        return $parent . DIRECTORY_SEPARATOR . basename($path);
    };
    $canonical = static fn(string $path): string => PHP_OS_FAMILY === 'Windows' ? strtolower(str_replace('\\', '/', $path)) : $path;
    $output = $resolveOutput($options['output']);
    $manifestPath = isset($options['manifest']) ? $resolveOutput($options['manifest']) : null;
    $inputKeys = [$canonical($input), $canonical($snapshot)];
    if (in_array($canonical($output), $inputKeys, true)) { throw new RuntimeException('Output must not replace an input.'); }
    if ($manifestPath !== null && in_array($canonical($manifestPath), [...$inputKeys, $canonical($output)], true)) { throw new RuntimeException('Manifest must be separate from both inputs and widget output.'); }
    $base = json_decode(file_get_contents($input), false, 512, JSON_THROW_ON_ERROR);
    $document = json_decode(file_get_contents($snapshot), false, 512, JSON_THROW_ON_ERROR);
    [$asset, $manifest] = AddOverlayFilters($base, $document);
    $temporaries = [];
    // Upstream asset helpers can call exit(), which bypasses finally blocks.
    register_shutdown_function(static function () use (&$temporaries): void {
        foreach ($temporaries as $path) { if (is_file($path)) { unlink($path); } }
    });
    try {
        require_once __DIR__ . '/../lib/uasset.php';
        $temporary = FilterWidgetTemporary($output);
        $temporaries[] = $temporary;
        SaveCompressedDecodedUasset($temporary, $asset, ['bakeAllIndices' => true, 'verbose' => false]);
        json_decode(file_get_contents($temporary), false, 512, JSON_THROW_ON_ERROR);
        $staged = [$output => $temporary];
        if ($manifestPath !== null) {
            $manifestJson = json_encode($manifest, JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR) . "\n";
            $manifestTemporary = FilterWidgetTemporary($manifestPath);
            $temporaries[] = $manifestTemporary;
            if (@file_put_contents($manifestTemporary, $manifestJson) !== strlen($manifestJson)) { throw new RuntimeException('Cannot write complete filter manifest.'); }
            json_decode(file_get_contents($manifestTemporary), false, 512, JSON_THROW_ON_ERROR);
            $staged[$manifestPath] = $manifestTemporary;
        }
        FilterWidgetCommitOutputs($staged);
    } finally {
        foreach ($temporaries as $path) { if (is_file($path)) { unlink($path); } }
    }
    echo 'Added ' . count($manifest['checkboxNames']) . " in-game filter checkboxes. Runtime execution remains to be verified.\n";
    return 0;
}

if (realpath($_SERVER['SCRIPT_FILENAME'] ?? '') === __FILE__) {
    try { exit(FilterWidgetMain($argv)); } catch (Throwable $error) { fwrite(STDERR, $error->getMessage() . "\n"); exit(1); }
}
