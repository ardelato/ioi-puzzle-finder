function FilterExpr(string $name, array $fields = []): object
{
    return (object)(['$type' => "UAssetAPI.Kismet.Bytecode.Expressions.EX_{$name}, UAssetAPI"] + $fields);
}

function FilterPointer(int $owner, string $name): object
{
    return (object)['$type' => 'UAssetAPI.Kismet.Bytecode.KismetPropertyPointer, UAssetAPI', 'New' => (object)[
        '$type' => 'UAssetAPI.UnrealTypes.FFieldPath, UAssetAPI', 'Path' => [$name], 'ResolvedOwner' => $owner,
    ]];
}

function FilterVariable(int $owner, string $name, bool $instance = false): object
{
    return FilterExpr($instance ? 'InstanceVariable' : 'LocalVariable', ['Variable' => FilterPointer($owner, $name)]);
}

function FilterCall(int $function, array $parameters = [], string $kind = 'CallMath'): object
{
    return FilterExpr($kind, ['StackNode' => $function, 'Parameters' => $parameters]);
}

/** UE4 VM sizes, not disk sizes: object/property pointers occupy eight bytes. */
function FilterExprSize(object $expression): int
{
    $token = explode(',', substr($expression->{'$type'}, strrpos($expression->{'$type'}, '.') + 1))[0];
    return match ($token) {
        'EX_Nothing', 'EX_Self', 'EX_True', 'EX_False', 'EX_EndOfScript' => 1,
        'EX_IntConst', 'EX_FloatConst', 'EX_Jump' => 5,
        'EX_ByteConst' => 2,
        'EX_NameConst' => 13,
        'EX_StringConst' => 2 + strlen($expression->Value),
        'EX_ObjectConst', 'EX_LocalVariable', 'EX_LocalOutVariable', 'EX_InstanceVariable' => 9,
        'EX_CallMath', 'EX_FinalFunction', 'EX_LocalFinalFunction' => 10 + array_sum(array_map('FilterExprSize', $expression->Parameters)),
        'EX_VirtualFunction' => 14 + array_sum(array_map('FilterExprSize', $expression->Parameters)),
        'EX_CallMulticastDelegate' => 10 + FilterExprSize($expression->Delegate) + array_sum(array_map('FilterExprSize', $expression->Parameters)),
        'EX_Let' => 9 + FilterExprSize($expression->Variable) + FilterExprSize($expression->Expression),
        'EX_LetBool' => 1 + FilterExprSize($expression->VariableExpression) + FilterExprSize($expression->AssignmentExpression),
        'EX_JumpIfNot' => 5 + FilterExprSize($expression->BooleanExpression),
        'EX_Context' => 13 + FilterExprSize($expression->ObjectExpression) + FilterExprSize($expression->ContextExpression),
        'EX_DynamicCast' => 9 + FilterExprSize($expression->TargetExpression),
        'EX_StructMemberContext' => 9 + FilterExprSize($expression->StructExpression),
        'EX_Return' => 1 + FilterExprSize($expression->ReturnExpression),
        default => throw new RuntimeException("Unsupported generated bytecode: {$token}"),
    };
}

function FilterContext(object $object, object $expression, object $property): object
{
    return FilterExpr('Context', ['ObjectExpression' => $object, 'Offset' => FilterExprSize($expression),
        'RValuePointer' => $property, 'ContextExpression' => $expression]);
}

function FilterStruct(string $name, string $type, array $value): object
{
    return (object)['$type' => 'UAssetAPI.PropertyTypes.Structs.StructPropertyData, UAssetAPI',
        'Name' => $name, 'StructType' => $type, 'SerializeNone' => true, 'Value' => $value];
}

function FilterVector(string $name, float $x, float $y): object
{
    return FilterStruct($name, 'Vector2D', [(object)['$type' => 'UAssetAPI.PropertyTypes.Structs.Vector2DPropertyData, UAssetAPI', 'Name' => $name,
        'Value' => (object)['$type' => 'UAssetAPI.UnrealTypes.FVector2D, UAssetAPI', 'X' => $x, 'Y' => $y]]]);
}

function FilterEnum(string $name, string $type, string $value): object
{
    $property = OverlayProperty('Enum', $name, $type . '::' . $value);
    $property->EnumType = $type;
    $property->InnerType = null;
    return $property;
}

function FilterArray(string $name, array $values): object
{
    $array = OverlayProperty('Array', $name, array_map(static fn(int $index): object => OverlayProperty('Object', '0', $index), $values));
    $array->ArrayType = 'ObjectProperty';
    return $array;
}

function FilterField(object $template, string $name, string $flags = 'CPF_None'): object
{
    $field = unserialize(serialize($template));
    $field->Name = $name;
    $field->PropertyFlags = $flags;
    $field->Flags = 'RF_Public';
    return $field;
}

function FilterFunction(object $template, int $index, int $owner, string $name, array $locals, array $code): object
{
    $function = unserialize(serialize($template));
    $function->{'$index'} = $index;
    $function->ObjectName = $name;
    $function->OuterIndex = $owner;
    $function->SuperStruct = 0;
    $function->SuperIndex = 0;
    $function->Children = [];
    $function->LoadedProperties = $locals;
    $function->FunctionFlags = 'FUNC_Public, FUNC_BlueprintCallable';
    $function->ScriptBytecode = $code;
    $function->ScriptBytecodeRaw = null;
    $function->ScriptBytecodeSize = array_sum(array_map('FilterExprSize', $code));
    $function->CreateBeforeSerializationDependencies = [];
    $function->SerializationBeforeSerializationDependencies = [];
    $function->CreateBeforeCreateDependencies = [$owner];
    // FunctionExport has its own eight-byte tail, distinct from normal widgets.
    $function->Extras = base64_encode(str_repeat("\0", 8));
    return $function;
}

function FilterReturn(): array
{
    return [FilterExpr('Return', ['ReturnExpression' => FilterExpr('Nothing')]), FilterExpr('EndOfScript')];
}

function FilterVoidPointer(): object
{
    return (object)['$type' => 'UAssetAPI.Kismet.Bytecode.KismetPropertyPointer, UAssetAPI', 'New' => (object)[
        '$type' => 'UAssetAPI.UnrealTypes.FFieldPath, UAssetAPI', 'Path' => [], 'ResolvedOwner' => 0,
    ]];
}

function FilterRadarMethod(int $owner, string $name, array $parameters = []): object
{
    return FilterContext(FilterVariable($owner, 'SSOverlayRadarState', true), FilterExpr('VirtualFunction', [
        'VirtualFunctionName' => $name, 'Parameters' => $parameters,
    ]), FilterVoidPointer());
}

/** Resolve forward jumps after the generated instruction sizes are known. */
function FilterCompileCode(array $parts): array
{
    $labels = [];
    $offset = 0;
    foreach ($parts as $part) {
        if (is_array($part)) { $labels[$part['label']] = $offset; }
        else { $offset += FilterExprSize($part); }
    }
    $code = [];
    foreach ($parts as $part) {
        if (is_array($part)) { continue; }
        if (isset($part->__target)) {
            if (!isset($labels[$part->__target])) { throw new RuntimeException('Missing generated jump label.'); }
            $part->CodeOffset = $labels[$part->__target];
            unset($part->__target);
        }
        $code[] = $part;
    }
    return $code;
}

/** Resolve the current gameplay HUD's radar, rather than an arbitrary old widget. */
function FilterRadarLookupCode(int $owner, int $function, array $native): array
{
    $local = static fn(string $name): object => FilterVariable($function, $name);
    $assign = static fn(string $name, object $value): object => FilterExpr('Let', ['Value' => FilterPointer($function, $name), 'Variable' => $local($name), 'Expression' => $value]);
    $radar = FilterVariable($owner, 'SSOverlayRadarState', true);
    $setRadar = static fn(object $value): object => FilterExpr('Let', ['Value' => FilterPointer($owner, 'SSOverlayRadarState'), 'Variable' => $radar, 'Expression' => $value]);
    $valid = static fn(string $name): object => FilterCall($native['IsValid'], [$local($name)]);
    $unless = static fn(object $condition, string $target): object => FilterExpr('JumpIfNot', ['CodeOffset' => 0, '__target' => $target, 'BooleanExpression' => $condition]);
    $jump = static fn(string $target): object => FilterExpr('Jump', ['CodeOffset' => 0, '__target' => $target]);
    $method = static fn(string $object, string $name, string $result): object => FilterContext($local($object), FilterCall($native[$name], [], 'FinalFunction'), FilterPointer($function, $result));
    return FilterCompileCode([
        $setRadar(FilterExpr('ObjectConst', ['Value' => 0])),
        $assign('CurrentPlayer', FilterCall($native['GetPlayerController'], [FilterExpr('Self'), FilterExpr('IntConst', ['Value' => 0])])),
        $unless($valid('CurrentPlayer'), 'Discover'),
        $assign('CurrentHud', FilterExpr('DynamicCast', ['ClassPtr' => $native['SophiaHUD'], 'TargetExpression' => $method('CurrentPlayer', 'GetHUD', 'CurrentHud')])),
        $unless($valid('CurrentHud'), 'Discover'),
        $assign('ExpectedOwner', FilterContext($local('CurrentHud'), FilterVariable($native['SophiaHUD'], 'GameHUDBaseWidget', true), FilterPointer($native['SophiaHUD'], 'GameHUDBaseWidget'))),
        ['label' => 'Discover'],
        FilterCall($native['GetAllWidgetsOfClass'], [FilterExpr('Self'), $local('RadarWidgets'), FilterExpr('ObjectConst', ['Value' => $native['RadarClass']]), FilterExpr('False')]),
        $assign('RadarIndex', FilterExpr('IntConst', ['Value' => 0])), ['label' => 'Candidate'],
        $unless(FilterCall($native['Less_IntInt'], [$local('RadarIndex'), FilterCall($native['Array_Length'], [$local('RadarWidgets')])]), 'Done'),
        FilterCall($native['Array_Get'], [$local('RadarWidgets'), $local('RadarIndex'), $local('RadarCandidate')]),
        $unless($valid('RadarCandidate'), 'Next'),
        $assign('OwnerObject', FilterCall($native['GetOuterObject'], [$local('RadarCandidate')])),
        $assign('OwnerObject', FilterCall($native['GetOuterObject'], [$local('OwnerObject')])),
        $unless($valid('ExpectedOwner'), 'ViewportFallback'),
        $unless(FilterCall($native['EqualEqual_ObjectObject'], [$local('OwnerObject'), $local('ExpectedOwner')]), 'Next'),
        $jump('Found'),
        ['label' => 'ViewportFallback'],
        $assign('OwnerWidget', FilterExpr('DynamicCast', ['ClassPtr' => $native['UserWidget'], 'TargetExpression' => $local('OwnerObject')])),
        $unless($valid('OwnerWidget'), 'Next'),
        $unless($method('OwnerWidget', 'IsInViewport', 'ViewportResult'), 'Next'),
        $assign('OwnerPlayer', $method('OwnerWidget', 'GetOwningPlayer', 'OwnerPlayer')),
        $unless(FilterCall($native['EqualEqual_ObjectObject'], [$local('OwnerPlayer'), $local('CurrentPlayer')]), 'Next'),
        ['label' => 'Found'],
        $setRadar(FilterExpr('DynamicCast', ['ClassPtr' => $native['RadarClass'], 'TargetExpression' => $local('RadarCandidate')])),
        $jump('Done'), ['label' => 'Next'],
        $assign('RadarIndex', FilterCall($native['Add_IntInt'], [$local('RadarIndex'), FilterExpr('IntConst', ['Value' => 1])])),
        $jump('Candidate'), ['label' => 'Done'], ...FilterReturn(),
    ]);
}

function FilterRadarPublishCode(int $owner, int $function, array $native): array
{
    $local = static fn(string $name): object => FilterVariable($function, $name);
    $assign = static fn(string $name, string $state): object => FilterExpr('Let', ['Value' => FilterPointer($function, $name), 'Variable' => $local($name), 'Expression' => FilterVariable($owner, $state, true)]);
    return FilterCompileCode([
        FilterExpr('JumpIfNot', ['CodeOffset' => 0, '__target' => 'Done', 'BooleanExpression' => FilterCall($native['IsValid'], [FilterVariable($owner, 'SSOverlayRadarState', true)])]),
        $assign('RadarSelectedTag', 'SSOverlaySelectedTag'),
        FilterExpr('LetBool', ['VariableExpression' => $local('RadarIncludeSites'), 'AssignmentExpression' => FilterVariable($owner, 'SSOverlaySource_spawn', true)]),
        FilterExpr('LetBool', ['VariableExpression' => $local('RadarEnabled'), 'AssignmentExpression' => FilterVariable($owner, 'SSOverlayRadarEnabled', true)]),
        $assign('RadarZoomIndex', 'SSOverlayRadarZoomIndex'), $assign('RadarSizeIndex', 'SSOverlayRadarSizeIndex'),
        FilterRadarMethod($owner, 'SSRadarSetView', [$local('RadarZoomIndex'), $local('RadarSizeIndex')]),
        FilterRadarMethod($owner, 'SSRadarSetSelection', [$local('RadarSelectedTag'), $local('RadarIncludeSites'), $local('RadarEnabled')]),
        ['label' => 'Done'], ...FilterReturn(),
    ]);
}

/** Pull keyboard changes before map actions; migrate state only to untouched replacement HUDs. */
function FilterRadarSyncCode(int $owner, int $function, array $native): array
{
    $local = static fn(string $name): object => FilterVariable($function, $name);
    $state = static fn(string $name): object => FilterVariable($owner, $name, true);
    $current = $state('SSOverlayRadarState');
    $shared = static fn(object $object, string $name): object => FilterContext($object, FilterVariable($native['RadarClass'], $name, true), FilterPointer($native['RadarClass'], $name));
    $unless = static fn(object $condition, string $target): object => FilterExpr('JumpIfNot', ['CodeOffset' => 0, '__target' => $target, 'BooleanExpression' => $condition]);
    $jump = static fn(string $target): object => FilterExpr('Jump', ['CodeOffset' => 0, '__target' => $target]);
    $same = static fn(): object => FilterCall($native['EqualEqual_ObjectObject'], [$local('PreviousRadar'), $current]);
    $pull = static fn(object $object): array => [
        FilterExpr('LetBool', ['VariableExpression' => $state('SSOverlayRadarEnabled'), 'AssignmentExpression' => $shared($object, 'SSRadarEnabled')]),
        FilterExpr('Let', ['Value' => FilterPointer($owner, 'SSOverlayRadarZoomIndex'), 'Variable' => $state('SSOverlayRadarZoomIndex'), 'Expression' => $shared($object, 'SSRadarZoomIndex')]),
        FilterExpr('Let', ['Value' => FilterPointer($owner, 'SSOverlayRadarSizeIndex'), 'Variable' => $state('SSOverlayRadarSizeIndex'), 'Expression' => $shared($object, 'SSRadarSizeIndex')]),
    ];
    $code = [
        FilterExpr('Let', ['Value' => FilterPointer($function, 'PreviousRadar'), 'Variable' => $local('PreviousRadar'), 'Expression' => $current]),
        $unless(FilterCall($native['IsValid'], [$local('PreviousRadar')]), 'Find'), ...$pull($local('PreviousRadar')),
        ['label' => 'Find'], FilterCall($native['FindRadar'], [], 'LocalFinalFunction'),
        $unless(FilterCall($native['IsValid'], [$current]), 'Controls'),
        $unless($state('SSOverlayRadarInitialized'), 'Pull'),
        $unless($same(), 'Replacement'), $jump('Pull'),
        ['label' => 'Replacement'],
        $unless(FilterCall($native['Less_IntInt'], [FilterExpr('IntConst', ['Value' => 0]), $shared($current, 'SSRadarRevision')]), 'Migrate'),
        ['label' => 'Pull'], ...$pull($current),
        $unless($state('SSOverlayRadarInitialized'), 'Controls'),
        $unless($same(), 'Migrate'), $jump('Controls'),
        ['label' => 'Migrate'], FilterCall($native['PublishRadar'], [], 'LocalFinalFunction'),
        ['label' => 'Controls'],
        FilterExpr('LetBool', ['VariableExpression' => $state('SSOverlayBatch'), 'AssignmentExpression' => FilterExpr('True')]),
        FilterExpr('LetBool', ['VariableExpression' => $local('CheckValue'), 'AssignmentExpression' => $state('SSOverlayRadarEnabled')]),
        FilterContext($state('SSOverlayCheck_radar_enabled'), FilterCall($native['SetIsChecked'], [$local('CheckValue')], 'FinalFunction'), FilterVoidPointer()),
        FilterExpr('LetBool', ['VariableExpression' => $state('SSOverlayBatch'), 'AssignmentExpression' => FilterExpr('False')]),
    ];
    foreach (['Zoom' => [50, 100, 200, 400], 'Size' => [100, 125, 150]] as $kind => $values) {
        foreach ($values as $index => $value) {
            $next = $kind . 'Label' . ($index + 1);
            $code[] = $unless(FilterCall($native['EqualEqual_IntInt'], [$state('SSOverlayRadar' . $kind . 'Index'), FilterExpr('IntConst', ['Value' => $index])]), $next);
            $label = $kind === 'Zoom' ? 'Radar range: ' . $value . ' m' : 'Size: ' . $value . '%';
            $code[] = FilterContext($state($kind === 'Zoom' ? 'SSOverlayRadarRangeText' : 'SSOverlayRadarSizeText'),
                FilterCall($native['SetText'], [FilterCall($native['Conv_StringToText'], [FilterExpr('StringConst', ['Value' => $label])])], 'FinalFunction'), FilterVoidPointer());
            $code[] = ['label' => $next];
        }
    }
    return FilterCompileCode([...$code, ...FilterReturn()]);
}

function FilterRefreshCode(int $owner, int $function, array $native): array
{
    $local = static fn(string $name): object => FilterVariable($function, $name);
    $assign = static fn(string $name, object $value): object => FilterExpr('Let', [
        'Value' => FilterPointer($function, $name), 'Variable' => $local($name), 'Expression' => $value,
    ]);
    $actorCall = static fn(int $method, array $parameters, string $result): object => FilterContext(
        $local('CurrentActor'), FilterCall($method, $parameters, 'FinalFunction'), FilterPointer($function, $result)
    );
    $tag = static fn(string $name): object => $actorCall($native['ActorHasTag'], [FilterExpr('NameConst', ['Value' => $name])], 'TagResult');
    $source = FilterCall($native['BooleanOR'], [
        FilterCall($native['BooleanOR'], [$tag('SaveStats.Source.static'), $tag('SaveStats.Source.hub')]),
        FilterCall($native['BooleanAND'], [FilterVariable($owner, 'SSOverlaySource_spawn', true), $tag('SaveStats.Source.spawn')]),
    ]);
    $getComponent = $actorCall($native['GetComponentByClass'], [FilterExpr('ObjectConst', ['Value' => $native['MarkerEmitter']])], 'Emitter');
    // StructMemberContext evaluates its struct expression using Stack.Object;
    // its object Context must be inside that expression, not around the member.
    $target = FilterExpr('StructMemberContext', [
        'StructMemberExpression' => FilterPointer($native['LocationMarkerData'], 'VisibleOnMap'),
        'StructExpression' => FilterContext($local('Emitter'), FilterVariable($native['MarkerEmitter'], 'Marker', true), FilterPointer($native['MarkerEmitter'], 'Marker')),
    ]);
    $loop = static function (string $prefix, object $visible) use ($native, $local, $assign, $getComponent, $target): array {
        return [
            $assign('Index', FilterExpr('IntConst', ['Value' => 0])), ['label' => $prefix],
            FilterExpr('JumpIfNot', ['CodeOffset' => 0, '__target' => $prefix . 'Done', 'BooleanExpression' => FilterCall($native['Less_IntInt'], [$local('Index'), FilterCall($native['Array_Length'], [$local('Actors')])])]),
            FilterCall($native['Array_Get'], [$local('Actors'), $local('Index'), $local('CurrentActor')]),
            FilterExpr('JumpIfNot', ['CodeOffset' => 0, '__target' => $prefix . 'Next', 'BooleanExpression' => FilterCall($native['IsValid'], [$local('CurrentActor')])]),
            $assign('Emitter', FilterExpr('DynamicCast', ['ClassPtr' => $native['MarkerEmitter'], 'TargetExpression' => $getComponent])),
            FilterExpr('JumpIfNot', ['CodeOffset' => 0, '__target' => $prefix . 'Next', 'BooleanExpression' => FilterCall($native['IsValid'], [$local('Emitter')])]),
            FilterExpr('LetBool', ['VariableExpression' => unserialize(serialize($target)), 'AssignmentExpression' => $visible]),
            ['label' => $prefix . 'Next'],
            $assign('Index', FilterCall($native['Add_IntInt'], [$local('Index'), FilterExpr('IntConst', ['Value' => 1])])),
            FilterExpr('Jump', ['CodeOffset' => 0, '__target' => $prefix]), ['label' => $prefix . 'Done'],
        ];
    };
    // Only a fresh widget needs an overlay-wide reset. Normal interactions hide
    // the prior type's cached actors and query the selected type directly.
    return FilterCompileCode([
        FilterCall($native['SyncRadar'], [], 'LocalFinalFunction'),
        FilterCall($native['PublishRadar'], [], 'LocalFinalFunction'),
        FilterExpr('JumpIfNot', ['CodeOffset' => 0, '__target' => 'FocusReady', 'BooleanExpression' => FilterCall($native['IsValid'], [FilterVariable($owner, 'SSOverlayRadarState', true)])]),
        FilterRadarMethod($owner, 'SSRadarRefreshPentadFocus'), FilterRadarMethod($owner, 'SSRadarRefreshAvailability'), ['label' => 'FocusReady'],
        $assign('Actors', FilterVariable($owner, 'SSOverlayPreviousActors', true)),
        FilterExpr('JumpIfNot', ['CodeOffset' => 0, '__target' => 'HidePrevious', 'BooleanExpression' => FilterVariable($owner, 'SSOverlayReset', true)]),
        FilterCall($native['GetAllActorsWithTag'], [FilterExpr('Self'), FilterExpr('NameConst', ['Value' => 'SaveStatsOverlay']), $local('Actors')]),
        FilterExpr('LetBool', ['VariableExpression' => FilterVariable($owner, 'SSOverlayReset', true), 'AssignmentExpression' => FilterExpr('False')]),
        ['label' => 'HidePrevious'], ...$loop('Hide', FilterExpr('False')),
        FilterCall($native['Array_Clear'], [$local('Actors')]),
        FilterExpr('JumpIfNot', ['CodeOffset' => 0, '__target' => 'QuerySelected', 'BooleanExpression' => FilterCall($native['EqualEqual_NameName'], [FilterVariable($owner, 'SSOverlaySelectedTag', true), FilterExpr('NameConst', ['Value' => 'None'])])]),
        FilterExpr('Jump', ['CodeOffset' => 0, '__target' => 'Cache']), ['label' => 'QuerySelected'],
        FilterCall($native['GetAllActorsWithTag'], [FilterExpr('Self'), FilterVariable($owner, 'SSOverlaySelectedTag', true), $local('Actors')]),
        ...$loop('Show', FilterCall($native['BooleanAND'], [$source, FilterCall($native['BooleanAND'], [FilterCall($native['Not_PreBool'], [FilterCall($native['IsActorSolved'], [$local('CurrentActor')], 'LocalFinalFunction')]), FilterCall($native['BooleanAND'], [FilterCall($native['AllowsPentadActor'], [$local('CurrentActor')], 'LocalFinalFunction'), FilterCall($native['IsActorAvailable'], [$local('CurrentActor')], 'LocalFinalFunction')])])])),
        ['label' => 'Cache'],
        FilterExpr('Let', ['Value' => FilterPointer($owner, 'SSOverlayPreviousActors'), 'Variable' => FilterVariable($owner, 'SSOverlayPreviousActors', true), 'Expression' => $local('Actors')]),
        FilterExpr('Let', ['Value' => FilterPointer($owner, 'SSOverlayProgressCursor'), 'Variable' => FilterVariable($owner, 'SSOverlayProgressCursor', true), 'Expression' => FilterExpr('IntConst', ['Value' => 0])]),
        ...FilterReturn(),
    ]);
}

/** Add dedicated controls and new functions; never rewrite existing function bytecode. */
function AddOverlayFilters(object $base, object $document, ?array $catalog = null): array
{
    if (!is_array($base->Exports ?? null) || !is_array($base->Imports ?? null) || ($document->schemaVersion ?? null) !== 2) {
        throw new RuntimeException('Expected a decoded map widget and a schemaVersion 2 marker document.');
    }
    $asset = unserialize(serialize($base));
    $byName = [];
    foreach ($asset->Exports as $index => $export) {
        if (str_starts_with($export->ObjectName ?? '', 'SSOverlay')) { throw new RuntimeException('Widget already contains overlay filters.'); }
        $byName[$export->ObjectName] = $index + 1;
    }
    foreach (['WBP_LargeMap_C', 'Default__WBP_LargeMap_C', 'WidgetTree', 'ComponentDelegateBinding_0', 'OnNextZoneClicked', 'ZoneNameText'] as $required) {
        if (!isset($byName[$required])) { throw new RuntimeException("Map widget is missing {$required}."); }
    }
    $classIndex = $byName['WBP_LargeMap_C'];
    $class = $asset->Exports[$classIndex - 1];
    $default = $asset->Exports[$byName['Default__WBP_LargeMap_C'] - 1];
    $treeIndex = $byName['WidgetTree'];
    $tree = $asset->Exports[$treeIndex - 1];
    $rootIndex = null;
    foreach ($tree->Data as $field) { if ($field->Name === 'RootWidget') { $rootIndex = $field->Value; } }
    if (!is_int($rootIndex) || $rootIndex <= 0) { throw new RuntimeException('WidgetTree has no root widget.'); }
    $root = $asset->Exports[$rootIndex - 1];
    if (($asset->Imports[-1 - $root->ClassIndex]->ObjectName ?? '') !== 'CanvasPanel') { throw new RuntimeException('Expected a canvas root for the map widget.'); }
    $normalTemplate = $tree;
    $functionTemplate = $asset->Exports[$byName['OnNextZoneClicked'] - 1];
    $propertyTemplates = [];
    foreach ($class->LoadedProperties as $property) { $propertyTemplates[$property->SerializedType] ??= $property; }
    $entry = $asset->Exports[0]->LoadedProperties[0];
    $boolTemplate = $propertyTemplates['BoolProperty'];
    $objectTemplate = $propertyTemplates['ObjectProperty'];
    $intTemplate = $entry;
    $arrayTemplate = $propertyTemplates['ArrayProperty'];
    $engine = OverlayImport($asset, '/Script/Engine', 0, '/Script/CoreUObject', 'Package');
    $game = OverlayImport($asset, '/Script/IslandsofInsight', 0, '/Script/CoreUObject', 'Package');
    $umg = OverlayImport($asset, '/Script/UMG', 0, '/Script/CoreUObject', 'Package');
    $native = [];
    foreach (['Actor', 'GameplayStatics', 'KismetArrayLibrary', 'KismetMathLibrary', 'KismetSystemLibrary', 'KismetTextLibrary', 'ActorComponent'] as $name) {
        $native[$name] = OverlayImport($asset, $name, $engine, '/Script/CoreUObject', 'Class');
    }
    $native['MarkerEmitter'] = OverlayImport($asset, 'MarkerEmitter', $game, '/Script/CoreUObject', 'Class');
    $native['LocationMarkerData'] = OverlayImport($asset, 'LocationMarkerData', $game, '/Script/CoreUObject', 'ScriptStruct');
    $radarPackage = OverlayImport($asset, '/Game/SaveStats/WBP_SSOverlayRadar', 0, '/Script/CoreUObject', 'Package');
    $native['RadarClass'] = OverlayImport($asset, 'WBP_SSOverlayRadar_C', $radarPackage, '/Script/UMG', 'WidgetBlueprintGeneratedClass');
    $core = OverlayImport($asset, '/Script/CoreUObject', 0, '/Script/CoreUObject', 'Package');
    $native['Object'] = OverlayImport($asset, 'Object', $core, '/Script/CoreUObject', 'Class');
    $native['PlayerController'] = OverlayImport($asset, 'PlayerController', $engine, '/Script/CoreUObject', 'Class');
    $native['SophiaHUD'] = OverlayImport($asset, 'SophiaHUD', $game, '/Script/CoreUObject', 'Class');
    $native['Widget'] = OverlayImport($asset, 'Widget', $umg, '/Script/CoreUObject', 'Class');
    $native['UserWidget'] = OverlayImport($asset, 'UserWidget', $umg, '/Script/CoreUObject', 'Class');
    $native['WidgetBlueprintLibrary'] = OverlayImport($asset, 'WidgetBlueprintLibrary', $umg, '/Script/CoreUObject', 'Class');
    foreach (['GetAllActorsWithTag' => 'GameplayStatics', 'Array_Get' => 'KismetArrayLibrary', 'Array_Length' => 'KismetArrayLibrary', 'Array_Clear' => 'KismetArrayLibrary', 'EqualEqual_NameName' => 'KismetMathLibrary',
        'BooleanAND' => 'KismetMathLibrary', 'BooleanOR' => 'KismetMathLibrary', 'Less_IntInt' => 'KismetMathLibrary', 'Add_IntInt' => 'KismetMathLibrary', 'EqualEqual_ObjectObject' => 'KismetMathLibrary', 'EqualEqual_IntInt' => 'KismetMathLibrary',
