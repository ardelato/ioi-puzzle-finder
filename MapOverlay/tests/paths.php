<?php

declare(strict_types=1);

/** External integration fixtures are never loaded from a developer's checkout. */
function OverlayTestDataPath(string $relative): string
{
    $root = getenv('IOI_RADAR_TEST_DATA_DIR');
    if (!is_string($root) || $root === '' || !is_dir($root)) {
        throw new RuntimeException('Set IOI_RADAR_TEST_DATA_DIR to an external fixture directory for this integration test.');
    }
    $path = rtrim($root, '/\\') . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, $relative);
    if (!is_file($path)) { throw new RuntimeException('Missing external integration fixture: ' . $relative); }
    return $path;
}

function OverlayTestAssetGui(): ?string
{
    $path = getenv('IOI_RADAR_ASSET_GUI');
    if (!is_string($path) || $path === '') { return null; }
    if (!is_file($path)) { throw new RuntimeException('IOI_RADAR_ASSET_GUI must name an existing UAssetGUI executable.'); }
    return $path;
}

/** Generated bytecode must store object-context call results in locals before passing them on. */
function AssertNoContextCallArguments(object $asset, string $label): void
{
    // Natives that read these arguments by value. Anything else (strings, text, structs, arrays)
    // is read by reference, which then points at the context object's property instead.
    $byValue = ['BooleanAND', 'BooleanOR', 'Not_PreBool', 'IsValid', 'EqualEqual_BoolBool', 'EqualEqual_IntInt', 'NotEqual_IntInt',
        'Less_IntInt', 'LessEqual_IntInt', 'Greater_IntInt', 'GreaterEqual_IntInt', 'Add_IntInt', 'Subtract_IntInt', 'Conv_ByteToInt', 'Conv_IntToString',
        'EqualEqual_ObjectObject', 'NotEqual_ObjectObject', 'EqualEqual_ByteByte'];
    // Wildcard array thunks take their item through MostRecentPropertyAddress.
    $itemArgument = ['Array_Add' => 1, 'Array_AddUnique' => 1, 'Array_Set' => 2, 'Array_Insert' => 1, 'Array_Contains' => 1, 'Array_Find' => 1, 'Array_RemoveItem' => 1];
    $plain = ['EX_LocalVariable', 'EX_InstanceVariable', 'EX_LocalOutVariable', 'EX_IntConst', 'EX_FloatConst', 'EX_ByteConst', 'EX_NameConst', 'EX_StringConst', 'EX_ObjectConst', 'EX_True', 'EX_False'];
    $kind = static fn(object $e): string => explode(',', substr($e->{'$type'} ?? '', strrpos($e->{'$type'} ?? '', '.') + 1))[0];
    $visit = static function (mixed $value, string $where) use (&$visit, $label, $asset, $byValue, $itemArgument, $plain, $kind): void {
        if (is_object($value)) {
            $node = $value->StackNode ?? null;
            $callee = is_int($node) && $node < 0 ? ($asset->Imports[-1 - $node]->ObjectName ?? '') : '';
            if ($callee !== '') {
                foreach ($value->Parameters ?? [] as $position => $argument) {
                    if ($kind($argument) === 'EX_Context' && isset($argument->ContextExpression->Parameters) && !in_array($callee, $byValue, true)) {
                        throw new RuntimeException($label . ' ' . $where . ': an object-context call is passed straight into ' . $callee . '; store it in a local first (by-reference parameters read the wrong address).');
                    }
                    if (($itemArgument[$callee] ?? null) === $position && !in_array($kind($argument), $plain, true)) {
                        throw new RuntimeException($label . ' ' . $where . ': ' . $callee . ' item must be a variable or literal, not ' . $kind($argument) . '.');
                    }
                }
            }
            foreach ((array)$value as $child) { $visit($child, $where); }
        } elseif (is_array($value)) { foreach ($value as $child) { $visit($child, $where); } }
    };
    foreach ($asset->Exports as $export) {
        if (!empty($export->ScriptBytecode)) { $visit($export->ScriptBytecode, $export->ObjectName); }
    }
}
